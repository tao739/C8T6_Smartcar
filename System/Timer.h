#ifndef __TIMER_H
#define __TIMER_H

#include "stm32f10x.h"

/*==============================================================================
 * 文件：Timer.h
 * 作用：1ms 系统时基（S1 负责）
 * 平台：STM32F103C8T6（本工程），标准外设库 SPL
 *----------------------------------------------------------------------------
 * 一、这个模块解决什么问题
 *   整车需要"每 1ms 做一次"的事情：按键消抖计数、LED 闪烁计时、
 *   蜂鸣器节奏计时。如果用 Delay_ms(1) 死等，CPU 就卡住了，串口会丢数据、
 *   10ms 的控制周期也会被拖乱。所以用 TIM2 每 1ms 产生一次中断，
 *   中断里只记一个数、举一个"到点了"的旗子，真正的活儿留给主循环干。
 *
 * 二、定时器参数怎么算出来是 1ms
 *   STM32F103 主频 72MHz，TIM2 挂在 APB1 上（定时器时钟 72MHz）：
 *      72MHz ÷ 72(PSC+1) = 1MHz  → 每 1 微秒计 1 个数
 *      1MHz ÷ 1000(ARR+1) = 1kHz → 每 1ms 溢出一次
 *   溢出就进 TIM2_IRQHandler 中断。
 *
 * 三、对外只暴露 4 个函数（主程序不需要知道定时器细节）
 *   Timer_Init()         初始化并启动 TIM2（整个程序只调用一次）
 *   Timer_GetMs()        取"开机以来过了多少毫秒"
 *   Timer_GetSec()       取"开机以来过了多少整秒"（= 毫秒 / 1000）
 *   Timer_TakeFlag1ms()  问"新的一毫秒到了吗"：到了返回 1 并清标志
 *
 * 四、主循环里的标准用法
 *   Timer_Init();                       // 初始化时调一次
 *   while (1) {
 *       if (Timer_TakeFlag1ms() == 0) { continue; }   // 没到 1ms 就继续转
 *       Key_Tick1ms();                                // 到了：跑 1ms 任务
 *       LED_Tick1ms();
 *       Buzzer_Tick1ms();
 *   }
 *   注意：TakeFlag 是"取走式"的——取一次就清一次，
 *         保证 1ms 任务每毫秒恰好执行一次（不清的话主循环会疯跑）。
 *
 * 五、资源占用
 *   只用 TIM2 一个定时器，不占用任何引脚。
 *   C8T6 板资源分配（H 的引脚图）：
 *     TIM2 = 本文件 1ms 时基
 *     TIM4 = 电机 PWM（PB6/PB7，S3 用）
 *     TIM3 = 编码器 A（PB4/PB5，可选，需部分重映射 + 关 JTAG，S3 用）
 *     TIM1 = 【空闲】蜂鸣器改成有源后用 GPIO 开关，不再占 TIM1
 *   ⚠ 编码器B 按 H 的图要用 TIM2（PA15/PB3），届时时基需要让位，
 *     当前开环方案不用编码器，所以 TIM2 归本模块。
 *============================================================================*/

void     Timer_Init(void);			/* 初始化 TIM2，每 1ms 中断一次 */
uint32_t Timer_GetMs(void);			/* 开机以来的毫秒数（中断里累加） */
uint32_t Timer_GetSec(void);		/* 开机以来的整秒数（毫秒/1000，向下取整） */
uint8_t  Timer_TakeFlag1ms(void);	/* 取 1ms 到点标志：1=有新的一毫秒，取走即清 */

#endif
