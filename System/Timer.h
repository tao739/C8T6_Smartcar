#ifndef __TIMER_H
#define __TIMER_H

#include "stm32f10x.h"

/*==============================================================================
 * Timer.h —— 1ms 系统时基（S1）
 *----------------------------------------------------------------------------
 * 用 TIM2 每 1ms 产生一次中断，对外只暴露"读毫秒数"和"取 1ms 标志"两个接口。
 * 其它模块（按键/LED/蜂鸣器/状态机）只依赖这里，不需要知道用的是哪个定时器、
 * 分频多少、中断怎么配 —— 以后换成 SysTick 或 TIM3，只改 Timer.c。
 *
 * 为什么不用 Delay_ms 当节拍：
 *   Delay 是死等，串口一打印（一行几十字节 ≈ 几毫秒）就把 10ms 控制周期拖歪，
 *   而 S2 的 Task1 是按"每 10ms 调用一次"累计时间判超时的，节拍一歪就不准。
 *
 * 用法：
 *   Timer_Init();                                  // 初始化时调用一次
 *   if (Timer_TakeFlag1ms()) { ... }               // 主循环里：这一毫秒到了吗
 *   uint32_t t = Timer_GetMs();                    // 取开机毫秒数
 *============================================================================*/

void     Timer_Init(void);				/* 启动 TIM2，每 1ms 中断一次 */
uint32_t Timer_GetMs(void);				/* 开机以来经过的毫秒数 */
uint32_t Timer_GetSec(void);			/* 开机以来经过的秒数 */
uint8_t  Timer_TakeFlag1ms(void);		/* 取 1ms 到点标志（取过自动清零，只返回一次 1） */

#endif
