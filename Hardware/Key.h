#ifndef __KEY_H
#define __KEY_H

#include "stm32f10x.h"

/*==============================================================================
 * Key.h —— 按键驱动（S1）
 *----------------------------------------------------------------------------
 * C8T6 过渡板的按键只有 1 个：
 *   KEY = PB9（图上标的 KEY2），按键另一端接 GND，内部上拉，按下 = 低电平
 *
 * 用这一个键完成所有操作：
 *   短按（按下再松开）       → KEY_EVT_START：待启动时启动；完成/异常后复位
 *   长按 ≥1000ms（按住不放） → KEY_EVT_STOP ：运行中急停（安全保护）
 *
 * 说明：长按事件在"按满 1 秒那一刻"就产生，不用等松手，急停更快；
 *       长按触发后松手不会再补发一个短按。
 *============================================================================*/

typedef enum
{
	KEY_EVT_NONE = 0,
	KEY_EVT_START,		/* 短按：启动 / 复位 */
	KEY_EVT_STOP		/* 长按 ≥1s：急停 */
} KeyEvent_t;

void       Key_Init(void);
void       Key_Tick1ms(void);			/* 每 1ms 调用一次 */
KeyEvent_t Key_GetEvent(void);			/* 取一个事件，没有则返回 NONE */
void       Key_Flush(void);				/* 清空未处理事件 */
uint8_t    Key_IsPressed(void);			/* 当前是否按住（调试用） */

#endif
