#ifndef __KEY_H
#define __KEY_H

#include "stm32f10x.h"

/*==============================================================================
 * 文件：Key.h
 * 作用：按键驱动（S1 负责）——消抖 + 短按/长按识别
 * 平台：STM32F103C8T6，按键 KEY = PB9（H 的引脚图上标"KEY2"）
 *----------------------------------------------------------------------------
 * 一、硬件接法（决定两个参数）
 *   按键一端接 PB9，另一端接 GND：
 *       松开 → 引脚被内部上拉拉高 = 高电平
 *       按下 → 引脚被短接到 GND   = 低电平
 *   所以：KEY_ACTIVE = 0（0 表示"按下低电平"），引脚配置为"输入上拉 IPU"。
 *   如果你的板子按键另一端接的是 3.3V（按下为高），把 KEY_ACTIVE 改成 1，
 *   代码会自动切成"输入下拉 IPD"并反转读取逻辑，不用改别的地方。
 *
 * 二、两种按键事件
 *   KEY_EVT_START：短按（按下后松开，全程 < 1 秒）
 *                  待启动时 = 一键启动；完成/异常后 = 复位
 *   KEY_EVT_STOP ：长按（按住不放满 1 秒，在"满 1 秒那一刻"产生，不用等松手）
 *                  运行中 = 急停（安全保护）
 *
 * 三、为什么这样设计（答辩常问）
 *   1) 非阻塞：每 1ms 由 Key_Tick1ms() 采一次电平，采完立刻返回，
 *      不像 Delay_ms(20) 那样把 CPU 卡住，串口/感知/电机控制都不受影响。
 *   2) 20ms 计数消抖：机械按键按下瞬间会抖动（几毫秒内高低乱跳），
 *      要求"电平连续 20 次（20ms）都一样"才承认，抗干扰能力强。
 *   3) 事件队列化：按键扫描在 1ms 节拍里跑，动作在主循环里执行，
 *      两者通过 Key_GetEvent() 传递一个"事件"，取走即清空，不会重复触发。
 *   4) 短按/长按互斥：长按触发后松手不会再补发一个短按（用 s_long_fired 保证），
 *      避免"长按急停"松手后又触发一次"启动/复位"。
 *
 * 四、标准用法（main.c 里就是这么写的）
 *   Key_Init();                    // 初始化时调一次
 *   while (1) {
 *       if (Timer_TakeFlag1ms()) { // 每 1ms
 *           Key_Tick1ms();         // ① 推进按键扫描
 *           ...
 *           switch (Key_GetEvent()) {   // ② 取事件并处理
 *               case KEY_EVT_START: ... break;
 *               case KEY_EVT_STOP:  ... break;
 *               default: break;
 *           }
 *       }
 *   }
 *============================================================================*/

/* 按键事件类型 */
typedef enum
{
	KEY_EVT_NONE = 0,	/* 0：没有事件（事件"信箱"是空的） */
	KEY_EVT_START,		/* 1：短按 —— 启动 / 复位 */
	KEY_EVT_STOP		/* 2：长按满 1 秒 —— 急停 */
} KeyEvent_t;

void       Key_Init(void);			/* 初始化 PB9 为输入上拉，清空内部状态 */
void       Key_Tick1ms(void);		/* 扫描一次，必须每 1ms 调用一次 */
KeyEvent_t Key_GetEvent(void);		/* 取一个事件（取走后清空） */
void       Key_Flush(void);			/* 丢掉未处理的事件（启动/复位时防误触发） */
uint8_t    Key_IsPressed(void);		/* 当前是否按住（调试用，1=按住） */

#endif
