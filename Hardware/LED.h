#ifndef __LED_H
#define __LED_H

#include "stm32f10x.h"

/*==============================================================================
 * 文件：LED.h
 * 作用：指示灯驱动（S1）—— 1 颗 LED，非阻塞闪烁/脉冲
 * 平台：STM32F103C8T6，LED = PB12（H 的引脚图上标"LED 板载"）
 *----------------------------------------------------------------------------
 * 硬件接法（固定，不做极性切换）：
 *     3.3V ──[限流电阻]── LED 阳极 → 阴极 ── PB12
 *   → PB12 输出【低电平】时灯亮，输出【高电平】时灯灭。
 *
 * 灯光与考核要求的对应：
 *   待启动     → 慢闪（500ms 亮 / 500ms 灭）：表示已上电、可以按键
 *   启动瞬间   → 亮 300ms 后自动灭（"出发"提示）
 *   运行中     → 灭（考核不要求行驶中亮灯）
 *   经过标志点 → 亮 400ms 后自动灭（LED_Pulse，配蜂鸣器 = 声光提示）
 *   完成/停车  → 常亮保持（明显区别于"亮一下"，直到复位）
 *   异常/急停  → 快闪（100ms 亮 / 100ms 灭）
 *
 * 三个接口的分工：
 *   LED_Set(on)          常亮 / 常灭
 *   LED_SetPattern(pat)  让灯自动闪（慢闪 / 快闪）
 *   LED_Pulse(ms)        亮一下，ms 毫秒后自动灭
 *
 * 用法：初始化时调一次 LED_Init()，之后每 1ms 调用一次 LED_Tick1ms()。
 *============================================================================*/

/* 闪烁花样 */
typedef enum
{
	LED_PAT_OFF = 0,		/* 0：常灭 */
	LED_PAT_ON,				/* 1：常亮 */
	LED_PAT_SLOW,			/* 2：慢闪（500ms 亮，500ms 灭） */
	LED_PAT_FAST			/* 3：快闪（100ms 亮，100ms 灭） */
} LedPattern_t;

void LED_Init(void);					/* 初始化 PB12 为推挽输出，上电默认灭 */
void LED_Set(uint8_t on);				/* 常亮(传 1) / 常灭(传 0) */
void LED_SetPattern(LedPattern_t pat);	/* 切换闪烁花样 */
void LED_Pulse(uint16_t ms);			/* 亮 ms 毫秒后自动熄灭（"亮一下"） */
void LED_AllOff(void);					/* 立即熄灭，并取消正在进行的脉冲 */
void LED_Tick1ms(void);					/* 推进闪烁/脉冲，必须每 1ms 调用一次 */

#endif
