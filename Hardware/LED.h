#ifndef __LED_H
#define __LED_H

#include "stm32f10x.h"

/*==============================================================================
 * LED.h —— 指示灯驱动（S1）
 *----------------------------------------------------------------------------
 * C8T6 过渡板只有 1 颗 LED：LED = PB12（板上标"LED 板载"）
 *
 * 按考核要求设计（"平时灭，到标志点才亮"）：
 *   待启动      → 慢闪   （表示已上电、可以按键，不属于"运行"）
 *   启动瞬间    → 亮 300ms 脉冲（"出发"提示）
 *   运行中      → 灭     ← 考核要求：正常行驶时不需要灯
 *   到标志点    → 亮 400ms 脉冲（配合蜂鸣器 = 声光提示）
 *   完成/停车   → 常亮保持（与"途经亮一下"明显不同，直到复位）
 *   异常/急停   → 快闪   （配合五声急促）
 *
 * 全部由 LED_Tick1ms() 推进，非阻塞、不占用定时器。
 *============================================================================*/

typedef enum
{
	LED_PAT_OFF = 0,		/* 常灭 */
	LED_PAT_ON,				/* 常亮 */
	LED_PAT_SLOW,			/* 慢闪 500ms 亮 / 500ms 灭 */
	LED_PAT_FAST			/* 快闪 100ms 亮 / 100ms 灭 */
} LedPattern_t;

void LED_Init(void);
void LED_Set(uint8_t on);					/* 常亮 / 常灭 */
void LED_SetPattern(LedPattern_t pat);		/* 切换闪烁花样 */
void LED_Pulse(uint16_t ms);				/* 一次性点亮 ms 毫秒后自动熄灭 */
void LED_AllOff(void);
void LED_Tick1ms(void);						/* 每 1ms 调用一次 */

#endif
